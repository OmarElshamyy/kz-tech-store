export function TrustSection({
  trustConfig = DEFAULT_STOREFRONT_CONFIG.trust,
}: {
  trustConfig?: StorefrontConfig["trust"];
}) {
  const items =
    trustConfig.items?.length > 0 ? trustConfig.items : DEFAULT_STOREFRONT_CONFIG.trust.items;

  if (!trustConfig.enabled || items.length === 0) return null;

  return (
    <section className="trust-section" aria-label="Why shop with us">
      <div className="section-heading">
        <p className="category-label">{trustConfig.kicker}</p>
        <h2>{trustConfig.title}</h2>
      </div>
      <div className="trust-grid">
        {items.map((item, idx) => (
          <div key={item.id + idx} className="trust-card">
            <span className="trust-icon" aria-hidden="true">
              {ICONS[idx % ICONS.length]}
            </span>
            <h3>{item.title}</h3>
            <p>{item.desc}</p>
          </div>
        ))}
      </div>
    </section>
  );
}
